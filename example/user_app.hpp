// example/user_app.hpp
// ---------------------------------------------------------------------------
// Публичный интерфейс приложения. Приложение НЕ включает платформенные
// заголовки напрямую — только ядро ОС через "os/...".
// ---------------------------------------------------------------------------
#pragma once

#include "os/common.hpp"
#include "os/core/task/sheduler.hpp"

/// Зарегистрировать задачи приложения в планировщике.
/// Возвращает Status::Ok, если все задачи созданы.
embed::Status user_app_register(embed::scheduler& sched) noexcept;

/// Необязательный самотест (вызывается до запуска планировщика).
embed::Status user_app_selftest() noexcept;

/// Демонстрация работы драйвера АЦП.
embed::Status user_app_adc_demo() noexcept;

/// Демонстрация асинхронного ввода-вывода с линейным кодом.
embed::Status user_app_async_demo() noexcept;

/// Зарегистрировать участников сторожевого таймера (до Service::start()).
///
/// Участник — это то, что ОБЯЗАНО работать: задача отмечается в конце своего
/// цикла, а сервис перестаёт кормить аппаратный таймер, если кто-то опоздал.
/// Возвращает Status::Ok, если все участники зарегистрированы.
embed::Status user_app_watchdog_register() noexcept;

/// Отчёт сторожа: сроки, кормления, причины отказа и посмертная запись
/// прошлой загрузки.
void user_app_report_watchdog() noexcept;

/// Предупреждение сторожа (Mode::Warning): вызывается ИЗ ПРЕРЫВАНИЯ ТИКА перед
/// тем, как устройство сбросится. Обязано быть коротким — без блокировок, сна
/// и обмена по шинам; задача колбэка — успеть отметить факт.
void user_app_watchdog_warning(void* arg) noexcept;

/// Отчёт о потреблении RAM: статические ёмкости ядра, куча, пул стеков
/// и водяные знаки стеков задач.
///
/// Водяной знак показывает РЕАЛЬНЫЙ пик использования стека, поэтому
/// печатайте отчёт ПОСЛЕ того, как задачи поработали: по нему видно,
/// можно ли уменьшить стек и сколько RAM освободится.
void user_app_report_ram() noexcept;

/// Отчёт энергосбережения: загрузка CPU по окнам, время в простое и в
/// глубоком сне, причины отказов от глубокого сна.
///
/// Печатать после того, как система поработала: это единственный честный
/// способ выбрать СТАТИЧЕСКИЙ профиль частоты — по измеренному пику нагрузки
/// считается, влезает ли работа в пониженную частоту
/// (power::project_load_percent).
void user_app_report_power() noexcept;
