// МОДЕЛЬ ПЕРЕХОДА К ДРУГОЙ ПРОШИВКЕ ДЛЯ MOCK-СБОРКИ.
//
// На хосте прыжок невозможен: нельзя «передать управление» по адресу 0x08004000
// в памяти процесса. Но решение загрузчика — а это самая рискованная часть
// системы — обязано быть проверяемым, поэтому здесь моделируется РЕЗУЛЬТАТ:
//   * какой адрес выбран;
//   * какой адрес был бы записан в VTOR (таблица векторов);
//   * что прерывания были бы запрещены до перехода.
// Модель также хранит «вектор сброса» по каждому адресу: так проверяется, что
// загрузчик не прыгает в стёртый или чужой участок (проверка правдоподобия
// образа — та же логика, что на STM32 читает первые два слова).
// ---------------------------------------------------------------------------
#include "../../os/iplatform.hpp"

namespace embed::mock_platform {

/// Границы RAM «кристалла» (20 КБ, как у STM32F103RB).
inline constexpr uint32_t kRamBase = 0x20000000u;
inline constexpr uint32_t kRamSize = 20u * 1024u;

/// Модель перехода.
struct BootModel {
    /// Адрес, на который «прыгнули» (0 — не прыгали).
    uint32_t jumped_to = 0u;
    /// Сколько раз прыгали.
    uint32_t jumps = 0u;
    /// Значение, записанное в VTOR (таблица векторов текущего образа).
    uint32_t vectors = 0u;
    /// Запрещались ли прерывания перед прыжком.
    bool irq_disabled = false;
    /// Системный тик остановлен (иначе он увёл бы ядро в таблицу векторов
    /// прежнего образа).
    bool systick_stopped = false;
    /// Прыжок запрещён: проверка правдоподобия обязана провалиться.
    bool jump_fails = false;

    void reset() noexcept {
        jumped_to = 0u;
        jumps = 0u;
        vectors = 0u;
        irq_disabled = false;
        systick_stopped = false;
        jump_fails = false;
    }
};

BootModel& boot_model() noexcept;

/// Таблица контракта для platform::ops().
const platform::BootOps& mock_boot_ops() noexcept;

} // namespace embed::mock_platform
