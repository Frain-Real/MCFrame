//   * хостовые тесты (MCFRAME_STM32_REGS_FAKE) — та же CMSIS (значит, те же
//     имена регистров, те же битовые маски и те же номера IRQ), но указатели
//     USART1/I2C1/RCC/NVIC подменяются на программную модель
//     (tests/host/stm32_regs_fake.hpp).
//
// Ветвление «для теста» есть ТОЛЬКО здесь: в автоматах драйверов его нет,
// поэтому тест проверяет ровно тот код, который уходит в прошивку.
// ---------------------------------------------------------------------------

