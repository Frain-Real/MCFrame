#pragma once
// ---------------------------------------------------------------------------
// ЭНЕРГОСБЕРЕЖЕНИЕ НА STM32F103: Sleep (WFI), DeepSleep (STOP + RTC) и
// статический профиль частоты.
//
// ПОЧЕМУ ЭТО ПРОВЕРЯЕТСЯ НА ПК
// Реализация (power_stm32.cpp) обращается к регистрам ТОЛЬКО через
// stm32_regs.hpp, поэтому один и тот же файл собирается и в прошивку, и в
// хостовый набор: tests/host/stm32_regs_fake.hpp подменяет MMIO программной
// моделью RTC/PWR/EXTI. Веток «для теста» в коде нет. Так проверяется
// ПОСЛЕДОВАТЕЛЬНОСТЬ работы с регистрами, не имея платы: ошибка в ней на
// железе выглядит как «уснул и не проснулся».
//
// ЧТО ИМЕННО ДЕЛАЕТ DEEP SLEEP (STOP mode)
//   1. останавливает SysTick (иначе первое же прерывание тика выведет ядро
//      из STOP через 1–10 мс, и сна не будет);
//   2. программирует будильник RTC на now + max_ms (округление ВВЕРХ до
//      секунды: разрешение будильника RTC на STM32F1 — одна секунда);
//   3. разрешает пробуждение по линии EXTI17 (будильник RTC) в NVIC;
//   4. гасит тактирование: PWR_CR_LPDS/D PDDS=0, SCB->SCR SLEEPDEEP, WFI;
//   5. после выхода снимает флаги (PWR WUF, EXTI PR, RTC ALRF), ВОССТАНАВЛИВАЕТ
//      тактирование (после STOP ядро работает от HSI 8 МГц) и системный тик;
//   6. возвращает ИЗМЕРЕННОЕ по RTC время сна — по нему ядро продвигает
//      монотонное время (SysTick проспанное не считал).
//
// ЧЕГО ЗДЕСЬ НЕТ
// Пробуждения по внешнему событию (кнопка/датчик на EXTI-линии): это
// прикладная настройка линии, и она описана в README. Глубокий сон включается
// только при вооружённом RTC-будильнике — иначе ядро ушло бы в STOP навсегда.
//
// ВАЖНО ПРО ПРОВЕРКУ: код собран для STM32 (./build.sh stm32) и его логика
// покрыта хостовым набором на модели регистров, но на реальной плате он НЕ
// измерялся. Перед использованием включите глубокий сон осознанно и проверьте
// ток потребления и время пробуждения на своей плате.
// ---------------------------------------------------------------------------

#include "stm32_regs.hpp"
#include "../../os/common.hpp"   // Status

#include <cstdint>

// Глубокий сон (STOP + RTC) компилируется только по явному флагу сборки:
//   cmake .. -DMCU_TARGET=stm32 -DMCFRAME_STM32_DEEP_SLEEP=1
// По умолчанию 0 — не потому, что код не готов, а потому, что источник
// пробуждения (кварц RTC или LSI) обязан быть проверен на конкретной плате.
#ifndef MCFRAME_STM32_DEEP_SLEEP
#define MCFRAME_STM32_DEEP_SLEEP 0
#endif

namespace embed::stm32::power {

/// Источник тактирования RTC. От него зависит и точность, и цена:
/// LSE (32.768 кГц, внешний кварц) — точный, но требует кварца на плате;
/// LSI (~40 кГц, внутренний RC) — есть всегда, но уезжает на десятки
/// процентов, поэтому время сна измеряется по RTC и всё равно приблизительно.
enum class RtcClock : uint8_t { Lse = 0u, Lsi = 1u };

struct Config {
    /// Профиль частоты, применяемый на старте (до OsTimer::Start).
    platform::PowerProfile profile = platform::PowerProfile::Performance;

    /// Включать ли глубокий сон (STOP). Выключен по умолчанию: пока источник
    /// пробуждения не проверен на плате, «просто WFI» безопаснее.
    bool     deep_sleep_enabled = false;

    /// Тактирование RTC для будильника.
    RtcClock rtc_clock = RtcClock::Lsi;

    /// Запас к запрошенному времени сна, мс. Будильник округляется вверх до
    /// секунды, поэтому запас от 1000 мс и больше избавляет от «проснулись
    /// на секунду раньше срока».
    uint32_t wake_slack_ms = 1100u;

    /// Низкопотребляющий стабилизатор в STOP (LPDS=1). Ток падает с единиц
    /// миллиампер до единиц микроампер, но выход из сна занимает больше
    /// времени — учитывается порогом окупаемости в супервизоре.
    bool     low_power_regulator = true;
};

/// Инициализация: применяет профиль частоты и (если нужно) готовит RTC.
/// Вызывать ДО OsTimer::Init/Start — смена частоты после старта тика
/// запрещена (см. platform::PowerOps::set_profile).
Status init(const Config& cfg) noexcept;

/// Текущая конфигурация (для отчётов приложения).
const Config& config() noexcept;

platform::PowerProfile profile() noexcept;
uint32_t sysclk_hz() noexcept;

/// См. platform::PowerOps.
uint32_t caps() noexcept;
uint32_t set_profile(uint32_t profile) noexcept;
uint32_t deep_sleep_horizon_ms() noexcept;
uint32_t deep_sleep_granularity_ms() noexcept;
uint32_t deep_sleep(uint32_t max_ms) noexcept;

// ───────────────────────── Наблюдение (диагностика) ─────────────────────────
uint32_t deep_sleep_entries() noexcept;
uint32_t deep_sleep_total_ms() noexcept;
uint32_t deep_sleep_failures() noexcept;
/// Последняя ошибка подготовки сна (0 — ошибок не было).
Status   last_error() noexcept;

#if MCFRAME_STM32_DEEP_SLEEP
/// Тело прерывания будильника RTC (RTCAlarm_IRQHandler): снимает флаги.
/// Выход из STOP происходит ДО этого вызова — обработчик не «пробуждение»,
/// а уборка, поэтому он не обязан быть коротким сверх обычного.
void on_alarm_irq() noexcept;
#endif

} // namespace embed::stm32::power
