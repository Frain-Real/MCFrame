#pragma once
// ---------------------------------------------------------------------------
// ВСТРОЕННАЯ FLASH STM32F1: стирание страницы и программирование half-word.
//
// Это самая опасная операция в проекте: ошибка в ней стоит не «неверных
// данных», а стёртого кода работающей прошивки. Поэтому процедура разбита
// ровно так, как её описывает RM0008, и каждый шаг проверяется:
//
//   1. снять защиту (FLASH_KEYR двумя ключами) — без этого CR.PER/CR.PG
//      игнорируются, а запись в SR «уходит в никуда»;
//   2. дождаться BSY = 0 перед изменением CR (иначе установка бита теряется);
//   3. стереть страницу: CR.PER + AR = адрес страницы + CR.STRT, дождаться
//      конца, снять CR.PER;
//   4. записать данные: CR.PG, затем half-word за half-word по адресам,
//      дожидаясь конца каждой операции;
//   5. проверить SR на PGERR/WRPRTERR — «запись прошла» и «запись попала»
//      на Flash не одно и то же;
//   6. взвести защиту обратно (CR.LOCK).
//
// ЧЕГО ЗДЕСЬ НЕТ
//   * option bytes и защита от чтения: это работа программатора, а не
//     рантайма (неверный option byte делает устройство необновляемым);
//   * mass erase (CR.MER): одна ошибочная установка бита стирает всю Flash,
//     включая загрузчик. Стирание — только постранично и только по адресу,
//     который вызывающий уже проверил;
//   * запись 32-битными словами: у STM32F1 в medium density программирование
//     half-word, и «ускорение» 32-битной записью здесь не работает.
//
// ПОЧЕМУ ЗДЕСЬ СВОЙ СЧЁТЧИК ОЖИДАНИЯ, А НЕ ВЕЧНЫЙ ЦИКЛ
// Ожидание BSY в вечном цикле при отказе железа превращается в зависание
// внутри критической операции: сторожевой таймер сбросит устройство, но
// диагностики не останется. Ограниченное ожидание возвращает отказ, который
// вызывающий (OTA) увидит и запишет в отчёт.
// ---------------------------------------------------------------------------

#include "../../os/iplatform.hpp"

namespace embed::stm32::flash {

/// Сколько итераций ожидания BSY до признания отказа (при 72 МГц — заметно
/// больше любой реальной операции: страница стирается ~20-40 мс).
inline constexpr uint32_t kBusyTimeoutLoops = 2000000u;

/// Размер страницы стирания STM32F103 (medium density) — 1 КБ.
uint32_t page_size() noexcept;

/// Грануляр программирования — half-word.
uint32_t write_granularity() noexcept;

/// Размер Flash, КБ, — из регистра размера (0x1FFFF7E0), как это делает
/// загрузчик. Значение читается один раз и запоминается: регистр доступен
/// только для чтения, но чтение по этому адресу на некоторых клонах
/// «залипает», поэтому кэшируем.
uint32_t capacity_bytes() noexcept;

uint32_t base() noexcept;

/// Снять защиту. false — ключи не приняты (или уже снята: повторный вызов
/// возвращает true, чтобы не ломать идемпотентность).
bool unlock() noexcept;

/// Взвести защиту обратно.
void lock() noexcept;

bool locked() noexcept;

/// Стереть len байт с адреса addr. addr и len кратны page_size().
bool erase(uint32_t addr, uint32_t len) noexcept;

/// Записать len байт по addr. Место обязано быть стёртым.
/// Любое смещение/длина: невыровненные края достраиваются чтением-записью
/// half-word (второй байт при этом обязан быть 0xFF — так и есть после
/// стирания).
bool program(uint32_t addr, const void* data, uint32_t len) noexcept;

/// Прочитать len байт по addr (Flash отображена в адресное пространство).
bool read(uint32_t addr, void* data, uint32_t len) noexcept;

/// Таблица для platform::ops().
const platform::FlashOps& ops() noexcept;

} // namespace embed::stm32::flash
