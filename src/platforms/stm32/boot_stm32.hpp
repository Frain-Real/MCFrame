// ПЕРЕХОД К ОБРАЗУ ПРОШИВКИ НА STM32F1 (Cortex-M3).
//
// Это тот код, который в проекте может «убить» устройство: после передачи
// управления обратно в загрузчик не вернуться, а ошибка в порядке действий
// (таблица векторов не переставлена, прерывания не запрещены, SP не взят из
// образа) даёт отказ, который виден только на железе. Поэтому последовательность
// ровно такая, как её описывает ARM:
//
//   1. запретить прерывания (PRIMASK): любое прерывание между шагами ушло бы в
//      таблицу векторов ПРЕЖНЕГО образа — то есть в код, который мы уже
//      собираемся покинуть;
//   2. остановить SysTick: он — источник тика ОС, и после перехода он обязан
//      запускаться заново уже новым образом (иначе тик придёт в старый
//      обработчик);
//   3. сбросить pending-прерывания периферии (NVIC ICPR): иначе уже
//      защёлкнутое прерывание сработает сразу после разрешения и уйдёт в
//      таблицу нового образа, который к этому может быть ещё не готов;
//   4. поставить VTOR на адрес образа — после этого обработчики берутся из ЕГО
//      таблицы;
//   5. взять начальный SP из первого слова образа (__set_MSP);
//   6. перейти на обработчик сброса из второго слова (младший бит — бит Thumb,
//      его при переходе нужно снять).
//
// ЧЕГО ЗДЕСЬ НЕТ: деинициализации периферии. Загружаемый образ инициализирует
// её сам (он для этого и написан), а «полуразобранное» состояние хуже исходного:
// например, выключенный такт USART при живом объекте драйвера в новом образе
// выглядит как исправная периферия, которая молчит.
// ---------------------------------------------------------------------------

#include "../../os/iplatform.hpp"

namespace embed::stm32::boot {

/// Адрес текущей таблицы векторов (SCB->VTOR) — по нему приложение понимает,
/// в каком слоте оно исполняется.
uint32_t image_base() noexcept;

/// Похож ли участок [addr, addr+capacity) на образ прошивки: начальный SP
/// указывает в RAM и выровнен, обработчик сброса лежит внутри участка и
/// отмечен битом Thumb.
bool image_plausible(uint32_t addr, uint32_t capacity) noexcept;

/// Передать управление образу. НА МКУ НЕ ВОЗВРАЩАЕТСЯ (если образ годен).
bool jump(uint32_t addr) noexcept;

/// Переставить таблицу векторов (VTOR).
void relocate_vectors(uint32_t addr) noexcept;

/// Таблица для platform::ops().
const platform::BootOps& ops() noexcept;

} // namespace embed::stm32::boot
