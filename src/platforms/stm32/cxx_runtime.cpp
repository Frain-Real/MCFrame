// Минимальный C++ runtime для bare-metal newlib.
//
// Глобальные объекты с нетривиальным деструктором (например, статические
// Storage-адаптеры с virtual dtor) заставляют GCC генерировать
// __cxa_atexit(..., &__dso_handle). В новых newlib/libgcc символа
// __dso_handle может не быть, и линковка падает на hidden symbol.
// На устройстве статические деструкторы всё равно не вызываются (нет выхода
// из main), поэтому достаточно определить сам маркер.
// ---------------------------------------------------------------------------
extern "C" __attribute__((weak)) void* __dso_handle = nullptr;
