#pragma once
// ---------------------------------------------------------------------------
// СУПЕРВИЗОР ЭНЕРГОСБЕРЕЖЕНИЯ: сон устройства + статистика нагрузки на CPU.
//
// ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО
// Потребление МКУ складывается из двух слагаемых: ток в активном режиме
// (десятки миллиампер) и ток в простое (единицы микроампер в STOP). Поэтому
// экономия достигается не «медленной работой», а тем, что ядро БОЛЬШУЮ ЧАСТЬ
// ВРЕМЕНИ ВЫКЛЮЧЕНО. Именно этим управляет супервизор: он измеряет, сколько
// времени система реально простаивает, и решает, можно ли на этом простое
// остановить ядро (Sleep/WFI) или погасить тактирование целиком (DeepSleep).
//
// ЧТО ЗДЕСЬ ЕСТЬ
//   * учёт нагрузки: доля тиков, когда ядро исполняло задачи, а не idle;
//     считается в прерывании по одному сравнению указателя (см. on_tick);
//   * горизонт сна: сколько можно спать, не нарушив ни один известный срок
//     (таймеры/будильники ОС, спящие задачи, подсказка приложения);
//   * допуск глубокого сна: горизонт должен окупать вход/выход, никто не
//     должен удерживать систему (keep-awake), платформа должна гарантировать
//     пробуждение;
//   * корректировка времени ОС после глубокого сна (SysTick в STOP не считает).
//
// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ — РАЗДЕЛ «ЧАСТОТА»
// Супервизор НЕ переключает частоту ядра по нагрузке. Профиль частоты
// (Performance/LowPower) выбирается один раз при инициализации, а статистика
// нагрузки служит ИЗМЕРИТЕЛЬНЫМ прибором для этого выбора, а не контуром
// регулирования:
//   * на STM32F1 напряжение ядра не регулируется (нет VOS/voltage scaling),
//     поэтому энергия на инструкцию от частоты практически не зависит:
//     снизив частоту вдвое, мы работаем вдвое дольше тем же током;
//   * выгоднее «добежать до простоя»: 1 мс на 72 МГц + 99 мс STOP дают
//     средний ток в разы меньше, чем 9 мс на 8 МГц + 91 мс STOP;
//   * смена частоты на ходу ломает SysTick, делители USART/I2C (baud,
//     CCR), прескалер АЦП и требует переинициализации периферии — то есть
//     стоит дороже, чем экономит.
// Отсюда роль статистики: убедиться, что выбранный СТАТИЧЕСКИЙ профиль
// выдерживает нагрузку (project_load_percent) и что простой действительно
// уходит в сон (duty/load), а не тратится на busy-wait.
// ---------------------------------------------------------------------------

#include "../common.hpp"
#include "../iplatform.hpp"
#include "../config/time_config.hpp"

namespace embed::power {

/// Профиль частоты — словарь платформы (см. platform::PowerProfile).
using Profile = platform::PowerProfile;

/// В каком состоянии ядро проводит простой.
enum class Mode : uint8_t {
    Run       = 0u,   ///< не спали (простоя не было)
    Sleep     = 1u,   ///< WFI: ядро стоит, тактирование идёт
    DeepSleep = 2u    ///< STOP: тактирование погашено, время сна измеряет платформа
};

/// Настройка супервизора.
struct Config {
    /// Статический профиль частоты. Применяется в init(), пока системный тик
    /// не запущен: позже менять частоту нельзя (см. шапку файла).
    Profile  profile = Profile::Performance;

    /// Разрешить глубокий сон. По умолчанию ВЫКЛЮЧЕН: платформа обязана
    /// иметь вооружённый источник пробуждения, иначе система уснёт навсегда.
    bool     allow_deep_sleep = false;

    /// Длина окна измерения нагрузки, мс. Внутри окна нагрузка не показывается
    /// (накапливается); по закрытию — load_percent, пик и средняя.
    uint32_t window_ms = 1000u;

    /// Минимальный горизонт простоя, при котором глубокий сон окупается, мс.
    /// Складывается с гранулярностью пробуждения платформы: если будильник
    /// имеет секундное разрешение, реальный порог — deep_sleep_min_ms + 1000.
    uint32_t deep_sleep_min_ms = 8u;

    /// Верхняя граница одного сна (0 — без своего ограничения, берётся
    /// гарантия платформы). Нужна там, где приложение хочет просыпаться
    /// для самопроверки/сторожевого таймера.
    uint32_t deep_sleep_max_ms = 0u;
};

/// Снимок статистики. Читается из задачи, пишется в прерывании тика —
/// поэтому только через stats() (он берёт критическую секцию).
struct Stats {
    // ── Загрузка CPU ──
    uint32_t windows            = 0u;   ///< закрытых окон измерения
    uint32_t window_ms          = 0u;   ///< накоплено в ТЕКУЩЕМ окне
    uint32_t busy_ms            = 0u;   ///< из них ядро исполняло задачи
    uint32_t idle_ms            = 0u;   ///< из них ядро было в простое
    uint8_t  load_percent       = 0u;   ///< загрузка последнего закрытого окна
    uint8_t  peak_load_percent  = 0u;   ///< максимум по всем окнам
    uint8_t  avg_load_percent   = 0u;   ///< средняя по всем закрытым окнам

    // ── Сон ──
    uint32_t sleep_entries      = 0u;   ///< входов в Sleep (WFI)
    uint32_t deep_sleep_entries = 0u;   ///< входов в DeepSleep (STOP)
    uint32_t deep_sleep_ms      = 0u;   ///< суммарно проспано в STOP, мс

    // ── Почему не спали глубоко (диагностика, а не украшение) ──
    uint32_t refused_short      = 0u;   ///< горизонт короче порога окупаемости
    uint32_t refused_keep_awake = 0u;   ///< кто-то удерживает систему
    uint32_t refused_no_source  = 0u;   ///< платформа/источник пробуждения не готовы
    uint32_t deep_sleep_failed  = 0u;   ///< платформа не вошла в сон
};

/// Во сколько процентов превратится нагрузка load_percent, если перейти с
/// частоты from_hz на to_hz (нагрузка обратно пропорциональна частоте).
///
/// Это и есть ответ на вопрос «какую частоту выбрать»: результат >100
/// означает, что на этой частоте система не успеет за реальным временем,
/// то есть профиль не подходит, каким бы экономичным он ни выглядел.
/// Насыщение — 1000 %.
uint32_t project_load_percent(uint32_t load_percent,
                              uint32_t from_hz,
                              uint32_t to_hz) noexcept;

/// Супервизор энергосбережения.
class Supervisor {
public:
    static Supervisor& instance() noexcept {
        static Supervisor s;
        return s;
    }

    Supervisor(const Supervisor&)            = delete;
    Supervisor& operator=(const Supervisor&) = delete;

    /// Хук системного тика: OsTimer::RegisterSystemHook(&Supervisor::tick_hook, nullptr).
    ///
    /// Регистрировать ДО хука планировщика: супервизор должен увидеть то, что
    /// исполнялось в момент прерывания, а не результат работы планировщика
    /// в этом же тике.
    static void tick_hook(void*) noexcept { instance().on_tick(); }

    /// Инициализация: проверяет платформу, применяет статический профиль
    /// частоты (только пока системный тик не запущен) и сбрасывает счётчики.
    ///
    /// Возврат: Ok | AlreadyExists | NotSupported (профиль не поддержан) |
    /// Busy (профиль требует смены частоты, а тик уже идёт).
    Status init(const Config& cfg) noexcept;

    /// Изменить настройку на ходу: политика сна и окно измерения применяются
    /// сразу, уже накопленная статистика НЕ сбрасывается.
    ///
    /// Смена профиля частоты по-прежнему возможна только до старта тика —
    /// см. Config::profile. Возврат тот же, что у init, плюс Unavailable,
    /// если супервизор ещё не инициализирован.
    Status configure(const Config& cfg) noexcept;

    bool initialized() const noexcept { return inited_; }

    // ──────────── Удержание: «не спать глубоко» ────────────
    //
    /// Пока жив хотя бы один Lease, глубокий сон запрещён.
    ///
    /// Это не «оптимизация», а защита от зависания: в STOP гаснет тактирование
    /// периферии, поэтому незавершённый обмен (UART/I2C/DMA/АЦП), которого
    /// ждёт задача, не продвинется никогда. Прикладной код берёт Lease на
    /// время таких ожиданий; асинхронный ввод-вывод делает это сам
    /// (см. async_kernel.hpp).
    class Lease {
    public:
        Lease() noexcept = default;
        Lease(const Lease&)            = delete;
        Lease& operator=(const Lease&) = delete;

        Lease(Lease&& other) noexcept : held_(other.held_) { other.held_ = false; }
        Lease& operator=(Lease&& other) noexcept {
            if (this != &other) { release(); held_ = other.held_; other.held_ = false; }
            return *this;
        }

        ~Lease() noexcept { release(); }

        bool held() const noexcept { return held_; }

        /// Отпустить досрочно (идемпотентно).
        void release() noexcept;

    private:
        friend class Supervisor;
        explicit Lease(bool held) noexcept : held_(held) {}
        bool held_ = false;
    };

    /// Взять удержание. Если супервизор не инициализирован — вернётся
    /// недействительный Lease (спать глубоко всё равно некому).
    Lease keep_awake() noexcept;

    // ──────────── Подсказка приложения о сроке ────────────
    /// «Разбуди меня не позже чем через ms» (0 — снять подсказку).
    ///
    /// Нужно для внешних событий, о которых ядро не знает: опрос датчика по
    /// расписанию, сторожевой таймер, начало приёма пакета.
    void set_wake_hint_ms(uint32_t ms) noexcept;

    /// Источник ограничения сна: подсистема, у которой есть СВОЙ срок, не
    /// видимый ядру. Главный пример — сторожевой таймер: он считает и в
    /// глубоком сне, а кормить его там некому, поэтому сон дольше его срока
    /// означает сброс устройства.
    ///
    /// Две функции, а не одна, потому что сон меняет и состояние источника:
    /// пока система спит, её участники не могут отметиться, поэтому после
    /// пробуждения сроки обязаны начаться заново (иначе первый же тик после
    /// сна обнаружил бы «просрочку» у всех и сбросил устройство).
    struct SleepLimit {
        /// Сколько миллисекунд система может НЕ просыпаться
        /// (kNoDeadline — без ограничения).
        uint32_t (*limit_ms)(void* ctx) noexcept;
        /// Система спала slept_ms и проснулась (0 — пробуждение без сна).
        /// Вызывается из контекста задачи, а не из прерывания.
        void (*on_slept)(void* ctx, uint32_t slept_ms) noexcept;
    };

    /// Ёмкость таблицы источников (хватает на сторожевой таймер + запас).
    static constexpr unsigned kMaxSleepLimits = 2u;

    /// Зарегистрировать источник ограничения. Возврат: Ok | InvalidArg |
    /// NoMemory (таблица заполнена) | AlreadyExists.
    ///
    /// Регистрируется самим модулем (watchdog::Service), а не приложением, и
    /// работает ДО init() супервизора: таблица читается в простое, а init()
    /// её не очищает — иначе порядок инициализации решал бы, действует ли
    /// защита.
    Status add_sleep_limit(const SleepLimit& limit, void* ctx) noexcept;

    /// Сколько миллисекунд можно спать, не нарушив ни один известный срок.
    /// kNoDeadline — известных сроков нет (ограничение задаст платформа).
    uint32_t horizon_ms() noexcept;

    // ──────────── Точки входа ядра ────────────
    /// Тик (контекст прерывания): учёт нагрузки и закрытие окон измерения.
    void on_tick() noexcept;

    /// Простой (контекст idle-задачи): выбрать режим и уснуть.
    /// Вызывается планировщиком, если супервизор инициализирован.
    void on_idle() noexcept;

    // ──────────── Наблюдение ────────────
    Stats    stats() noexcept;
    Mode     last_mode() const noexcept { return last_mode_; }
    Profile  profile() const noexcept { return profile_; }
    uint32_t sysclk_hz() const noexcept { return sysclk_hz_; }
    /// Сколько раз асинхронный ввод-вывод/приложение удерживали систему
    /// от глубокого сна (для отчётов: «почему не спим»).
    uint32_t keep_awake_count() const noexcept { return keep_awake_; }

    /// Статическое потребление RAM супервизором (для отчёта о памяти).
    static constexpr Size static_bytes() noexcept { return sizeof(Supervisor); }

private:
    Supervisor() noexcept = default;

    /// Решение о сне, принятое под критической секцией.
    struct Plan {
        Mode     mode  = Mode::Run;
        uint32_t sleep_ms = 0u;   ///< запрошенный горизонт
    };

    Plan plan_idle() noexcept;
    /// Общая часть init()/configure(): нормализация, проверки, профиль частоты.
    Status apply_config(const Config& cfg) noexcept;
    /// Сообщить источникам ограничений, что система проспала slept_ms.
    void notify_slept(uint32_t slept_ms) noexcept;
    uint32_t horizon_locked() const noexcept;
    void close_window_locked() noexcept;
    void account_deep_sleep(uint32_t slept_ms) noexcept;

    Config   cfg_{};
    bool     inited_   = false;
    Profile  profile_  = Profile::Performance;
    uint32_t sysclk_hz_ = 0u;

    // Текущее окно измерения (пишется из прерывания тика — под Lock).
    uint32_t window_ms_      = 0u;
    uint32_t window_busy_ms_ = 0u;
    uint32_t window_idle_ms_ = 0u;

    // Итоги по закрытым окнам.
    uint32_t windows_        = 0u;
    uint64_t load_sum_       = 0u;   // сумма процентов закрытых окон
    uint8_t  last_load_      = 0u;
    uint8_t  peak_load_      = 0u;

    // Сон.
    uint32_t sleep_entries_      = 0u;
    uint32_t deep_entries_       = 0u;
    uint32_t deep_ms_            = 0u;
    uint32_t refused_short_      = 0u;
    uint32_t refused_keep_awake_ = 0u;
    uint32_t refused_no_source_  = 0u;
    uint32_t deep_failed_        = 0u;
    Mode     last_mode_          = Mode::Run;

    // Связь с приложением.
    uint32_t keep_awake_  = 0u;
    uint32_t wake_hint_ms_ = 0u;   // 0 — подсказки нет

    // Источники ограничения сна (сторожевой таймер и т.п.).
    const SleepLimit* limit_[kMaxSleepLimits]{};
    void*             limit_ctx_[kMaxSleepLimits]{};
    uint32_t          limit_count_ = 0u;
};

} // namespace embed::power
