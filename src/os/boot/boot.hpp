/// Адрес, по которому собран ЭТОТ образ — символ линкера `_os_image_base`.
///
/// Зачем это нужно, если платформа умеет отвечать на вопрос «где таблица
/// векторов» (`BootOps::image_base`): сразу после сброса VTOR ещё указывает на
/// ЗАГРУЗЧИК (или на начало Flash), а `SystemInit` живёт в библиотеке и собран
/// ОДИН раз для всех образов — задать ему смещение «на образ» через -D нельзя.
/// Поэтому приложение, собранное в слот, обязано переставить таблицу векторов
/// САМО, по адресу из линкера: см. relocate_vectors_to_self().
uint32_t linked_image_base() noexcept;

/// Переставить таблицу векторов на адрес СВОЕГО образа. Вызывать в начале
/// main, до разрешения прерываний и до настройки периферии.
///
/// Без этого приложение в слоте оставляет VTOR указывающим в таблицу
/// загрузчика: первое же прерывание (тик, приём байта) уводит управление в
/// чужой код — то есть в отказ, который потом ищут в драйверах.
///
/// Возврат: Ok — таблица на своём месте | NotFound — адрес образа неизвестен
/// (нет символа линкера; например сборка без линкер-скрипта: хостовые тесты) |
/// NotSupported — платформа не умеет переставлять.
Status relocate_vectors_to_self() noexcept;

