// ---------------------------------------------------------------------------
// ЗАГРУЗЧИК СО СТОРОНЫ ПРИЛОЖЕНИЯ.
//
// Отдельный заголовок, а НЕ часть boot.hpp, по одной причине: эти функции
// работают через сервис OTA (os/ota/ota.hpp), то есть тянут в образ протокол,
// SHA-256 и драйверы интерфейса. Загрузчику всё это не нужно — ему хватает
// меток и правила выбора слота, — и если бы эти функции лежали в boot.cpp,
// загрузчик на 128 КБ Flash не оставил бы места двум слотам.
//
// Что здесь есть:
//   * fill_ota_config() — заполнить ota::Config адресами слотов и активным
//     слотом ТЕКУЩЕЙ прошивки (по VTOR платформы, а не по константе сборки);
//   * confirm_self() — подтвердить пробную загрузку, когда приложение дошло до
//     конца инициализации;
//   * ota_is_available() — можно ли вообще обновляться из этого образа.
// ---------------------------------------------------------------------------

#include "boot.hpp"

#include "../ota/ota.hpp"

namespace embed::boot {

/// Заполнить `ota::Config` из раскладки: адреса слотов, метаданные и активный
/// слот ТЕКУЩЕЙ прошивки.
///
/// Возврат: Ok — настройка заполнена; NotFound — текущий образ не лежит ни в
/// одном слоте (прошит программатором «обычным» адресом): тогда обновляться из
/// него нельзя, и это не ошибка; InvalidArg — раскладка непригодна.
Status fill_ota_config(ota::Config& ota_cfg, const Config& boot_cfg) noexcept;

/// Подтвердить работу текущей прошивки, если загрузка была пробной.
///
/// Возврат: Ok — либо подтвердили, либо подтверждать нечего |
/// NotFound — меток нет (заводская прошивка) |
/// Unavailable — сервис OTA не инициализирован (подтверждать нечем) |
/// NotSupported — подтвердить не удалось (запись в носитель не прошла): об этом
/// приложение обязано сообщить, а не делать вид, что всё хорошо.
Status confirm_self(const Config& boot_cfg) noexcept;

/// Работает ли обновление в этом образе: он лежит в слоте и сервис OTA поднят.
bool ota_is_available(const Config& boot_cfg) noexcept;

} // namespace embed::boot
